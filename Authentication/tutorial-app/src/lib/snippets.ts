// The lab shows the exact files that were run before they went into a chapter. They live in /snippets (outside
// src, so this app does not type-check them) and are bundled as plain strings.
//
// Layout: snippets/<topic>/<stack>/<path inside that project>, for example "04-jwt/node/src/server.ts",
// "04-jwt/python/app.py" or "04-jwt/dotnet/Api/Program.cs". Every stack folder is a runnable project with its own
// tests; scripts/verify.mjs runs them all.
const files = import.meta.glob(
  [
    '../../snippets/**/*.{ts,mts,js,mjs,json,py,cs,csproj,props,txt,toml,ini,cfg,md,http,sh,yml,yaml,pem,html}',
    // Generated and installed files are never shown.
    '!../../snippets/**/node_modules/**',
    '!../../snippets/**/.venv/**',
    '!../../snippets/**/__pycache__/**',
    '!../../snippets/**/.pytest_cache/**',
    '!../../snippets/**/bin/**',
    '!../../snippets/**/obj/**',
    '!../../snippets/**/package-lock.json',
    // Private keys and test certificates are generated by the projects at run time, never stored.
    '!../../snippets/**/*.key.pem',
  ],
  { query: '?raw', import: 'default', eager: true },
) as Record<string, string>;

const PREFIX = '../../snippets/';

export function snippet(path: string): string {
  const source = files[PREFIX + path];
  if (source === undefined) throw new Error(`Snippet not found: snippets/${path}`);
  return source.replace(/\n+$/, '');
}

export const snippetPaths = Object.keys(files).map((key) => key.slice(PREFIX.length));

export type Stack = 'node' | 'python' | 'dotnet';
export const STACKS: Stack[] = ['node', 'python', 'dotnet'];
export const STACK_LABEL: Record<Stack, string> = { node: 'Node.js', python: 'Python', dotnet: '.NET' };

/** "04-jwt/node/src/server.ts" → { topic: "04-jwt", stack: "node", file: "src/server.ts" }. */
export function splitSnippetPath(path: string): { topic: string; stack: Stack | null; file: string } {
  const parts = path.split('/');
  if (parts.length < 2) throw new Error(`Snippet path needs a topic folder: ${path}`);
  const stack = (STACKS as string[]).includes(parts[1]) ? (parts[1] as Stack) : null;
  return { topic: parts[0], stack, file: parts.slice(stack ? 2 : 1).join('/') };
}
